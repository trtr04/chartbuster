# Writes data/artist_names.js: the artists that have a page in artist-profiles.html,
# so the explorer can link an artist's name only when a profile exists.
# Usage: python3 data/build_artist_names.py artist-profiles.html data/artist_names.js
import json, re, sys
src, out = sys.argv[1], sys.argv[2]
html = open(src, encoding="utf-8").read()
start = html.index("const D=") + len("const D=")
D = json.loads(html[start:html.index(",A=D.A", start)])
names = sorted(D["art"])
open(out, "w", encoding="utf-8").write("// Generated by build_artist_names.py from artist-profiles.html\nwindow.ARTIST_PROFILES = "
    + json.dumps(names, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(names), "artists")
