"""Build data/key_wheel.js for key-wheel.html from the Kaggle
'Spotify Tracks Dataset' (maharshipandya/-spotify-tracks-dataset, dataset.csv).

Usage:  python3 data/build_key_data.py path/to/dataset.csv data/key_wheel.js

Output (window.KEY_DATA):
  families : [[name, [genres...]], ...]  ("All" first)
  cells    : {family: [[key, mode, popBucket, count, valenceSum, energySum, tempoSum], ...]}
             popBucket = floor(popularity / 10), 0..10; aggregated so the page can
             filter by any popularity threshold that is a multiple of 10.
  examples : {family: {"key-mode": [[title, artist, popularity, trackId], ...]}}
             (top 5 most popular per key and mode)
Tracks listed under several genres are counted once overall and once per family.
"""
import csv, json, sys
from collections import defaultdict

FAMILIES = [
    ("Pop", ["pop", "indie-pop", "power-pop", "synth-pop", "pop-film", "k-pop", "j-pop",
             "cantopop", "mandopop", "j-idol", "british", "swedish", "french", "german"]),
    ("Hip-hop & R&B", ["hip-hop", "r-n-b", "soul", "funk", "groove", "gospel"]),
    ("Rock", ["rock", "alt-rock", "alternative", "indie", "hard-rock", "psych-rock", "grunge",
              "j-rock", "rock-n-roll", "rockabilly", "guitar", "emo", "goth"]),
    ("Metal & punk", ["metal", "heavy-metal", "black-metal", "death-metal", "metalcore",
                      "grindcore", "hardcore", "punk", "punk-rock", "industrial"]),
    ("Electronic", ["edm", "electronic", "electro", "house", "deep-house", "progressive-house",
                    "chicago-house", "techno", "detroit-techno", "minimal-techno", "trance",
                    "dubstep", "drum-and-bass", "breakbeat", "hardstyle", "garage", "idm",
                    "club", "dance", "j-dance", "disco", "trip-hop"]),
    ("Latin", ["latin", "latino", "reggaeton", "salsa", "samba", "pagode", "sertanejo", "forro",
               "mpb", "brazil", "tango", "spanish"]),
    ("Country & folk", ["country", "honky-tonk", "bluegrass", "folk", "acoustic",
                        "singer-songwriter", "songwriter"]),
    ("Jazz & blues", ["jazz", "blues", "ska", "reggae", "dub", "dancehall", "afrobeat"]),
    ("Classical & calm", ["classical", "opera", "piano", "ambient", "new-age", "sleep", "study",
                          "chill", "show-tunes"]),
]
FAMILY_OF = {g: f for f, gs in FAMILIES for g in gs}

src, out = sys.argv[1], sys.argv[2]
seen = defaultdict(set)                       # family -> track ids already counted
cells = defaultdict(lambda: defaultdict(lambda: [0, 0.0, 0.0, 0.0]))
examples = defaultdict(lambda: defaultdict(list))

for r in csv.DictReader(open(src, encoding="utf-8")):
    tid = r["track_id"]
    fams = ["All"] + ([FAMILY_OF[r["track_genre"]]] if r["track_genre"] in FAMILY_OF else [])
    key, mode, pop = int(r["key"]), int(r["mode"]), int(r["popularity"])
    if key < 0:
        continue
    for f in fams:
        if tid in seen[f]:
            continue
        seen[f].add(tid)
        c = cells[f][(key, mode, min(pop // 10, 10))]
        c[0] += 1
        c[1] += float(r["valence"]); c[2] += float(r["energy"]); c[3] += float(r["tempo"])
        examples[f][f"{key}-{mode}"].append((r["track_name"], r["artists"].replace(";", ", "), pop, tid))

data = {
    "families": [["All", []]] + [[f, gs] for f, gs in FAMILIES],
    "cells": {f: [[k, m, b, c[0], round(c[1], 2), round(c[2], 2), round(c[3], 1)]
                  for (k, m, b), c in sorted(v.items())] for f, v in cells.items()},
    "examples": {},
}
for f, byk in examples.items():
    data["examples"][f] = {}
    for km, lst in byk.items():
        lst.sort(key=lambda x: -x[2])
        top, names = [], set()
        for t in lst:                          # skip repeated titles by the same artist
            if (t[0].lower(), t[1]) in names:
                continue
            names.add((t[0].lower(), t[1])); top.append(list(t))
            if len(top) == 5:
                break
        data["examples"][f][km] = top

hdr = ("// Source: Kaggle 'Spotify Tracks Dataset' (maharshipandya), dataset.csv, 114k rows /\n"
       "// ~89.7k unique tracks. Generated by data/build_key_data.py. Key and mode are Spotify's\n"
       "// estimates (key 0 = C ... 11 = B; mode 1 = major, 0 = minor).\n")
open(out, "w", encoding="utf-8").write(hdr + "window.KEY_DATA = " +
                                       json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print({f: len(s) for f, s in seen.items()})
