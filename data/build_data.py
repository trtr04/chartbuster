import csv, json, re, sys
src, out = sys.argv[1], sys.argv[2]
rows = list(csv.DictReader(open(src, encoding="utf-8", errors="replace")))
PREFIX = "https://i.scdn.co/image/ab67616d0000b273"
def title(s):
    return re.sub(r"(^|[\s(\[\-/])([a-z])", lambda m: m.group(1) + m.group(2).upper(), s)
pct = lambda v: round(float(v) * 100)
songs, nopref = [], 0
for x in rows:
    img = x["image_url"]
    if img.startswith(PREFIX): img = img[len(PREFIX):]
    else: nopref += 1
    tid = x["spotify_url"].rsplit("/", 1)[-1]
    songs.append([title(x["track_name"]), x["artist_name"], int(x["track_album_release_date"][:4]),
                  pct(x["valence"]), pct(x["energy"]), pct(x["danceability"]), pct(x["acousticness"]),
                  pct(x["tempo"]), pct(x["track_popularity"]), x["playlist_genre"].upper() if x["playlist_genre"].lower() in ("edm","r&b") else x["playlist_genre"],
                  tid, img])
hdr = ("// Source: Kaggle 'Spotify Most Popular Songs Dataset' (rishabhpancholi1302), songs.csv, 900 tracks.\n"
       "// Generated by build_data.py. Audio features in the source are min-max scaled to 0-1 across the dataset;\n"
       "// here they are x100. Fields: title, artist, year, mood(valence), energy, danceability, acousticness,\n"
       "// tempo (relative 0-100, not BPM), popularity (relative 0-100), genre, spotifyTrackId, albumArtHash\n")
open(out, "w").write(hdr + "window.SONG_DATA = " + json.dumps(songs, ensure_ascii=False, separators=(",", ":")).replace("],[", "],\n[") + ";\n")
print(len(songs), "songs; non-standard image urls:", nopref)
